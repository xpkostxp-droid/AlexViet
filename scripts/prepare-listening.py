#!/usr/bin/env python3
"""Recreate Vietnamese-only lesson audio and typed content from supplied originals.
Requires Python 3 and ffmpeg; originals stay outside the public website.
Usage: python3 scripts/prepare-listening.py --audio-dir /path/to/originals
"""
import argparse, json, re, subprocess, unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SAMPLE_RATE=22050
GUARD_SECONDS=1.0

def tokens(text):
    return re.findall(r"[^\W\d_]+(?:-[^\W\d_]+)*",unicodedata.normalize('NFC',text).lower(),re.UNICODE)

def prepare(audio_dir):
    lessons=json.loads((ROOT/'scripts/listening/source-manifest.json').read_text())
    glossary={tuple(tokens(vi)): (vi.strip(),ru.strip()) for line in (ROOT/'scripts/listening/glossary.txt').read_text().splitlines() if line.strip() for vi,ru in [line.split('|',1)]}
    unknown=set()
    for lesson in lessons:
        vocabulary={}
        for phrase in lesson['phrases']:
            words=tokens(phrase['vi']);i=0
            while i<len(words):
                key=next((tuple(words[i:i+n]) for n in range(min(6,len(words)-i),0,-1) if tuple(words[i:i+n]) in glossary),None)
                if not key:unknown.add(words[i]);i+=1;continue
                vi,ru=glossary[key];vocabulary[key]={'vi':vi.strip(),'ru':ru};i+=len(key)
        lesson['vocabulary']=list(vocabulary.values())
    if unknown:raise ValueError('Untranslated vocabulary: '+', '.join(sorted(unknown)))
    output=[]
    for lesson in lessons:
        source=audio_dir/lesson['sourceTrack']
        pcm=subprocess.check_output(['ffmpeg','-v','error','-i',str(source),'-f','s16le','-ar',str(SAMPLE_RATE),'-ac','1','pipe:1'])
        combined=bytearray();phrases=[]
        for i,phrase in enumerate(lesson['phrases'],1):
            first=round(phrase['sourceStart']*SAMPLE_RATE)*2;last=round(phrase['sourceEnd']*SAMPLE_RATE)*2
            assert 0<=first<last<=len(pcm), (source,i)
            start=len(combined)/2/SAMPLE_RATE
            combined.extend(pcm[first:last])
            end=len(combined)/2/SAMPLE_RATE
            phrases.append({'id':f'{lesson["number"]:02}-{i:03}','vi':phrase['vi'],'ru':phrase['ru'],'start':round(start,5),'end':round(end,5)})
            combined.extend(bytes(round(GUARD_SECONDS*SAMPLE_RATE)*2))
        name=f'{lesson["number"]:02}.mp3'
        audio=ROOT/'public/audio/listening'/name;audio.parent.mkdir(parents=True,exist_ok=True)
        subprocess.run(['ffmpeg','-v','error','-y','-f','s16le','-ar',str(SAMPLE_RATE),'-ac','1','-i','pipe:0','-codec:a','libmp3lame','-b:a','96k','-map_metadata','-1',str(audio)],input=combined,check=True)
        output.append({'id':lesson['id'],'number':lesson['number'],'title':lesson['title'],'audio':f'audio/listening/{name}','vocabulary':lesson['vocabulary'],'phrases':phrases})
        print(name,len(phrases),'phrases',audio.stat().st_size,'bytes',flush=True)
    target=ROOT/'src/content/listening/lessons.ts'
    target.write_text('// Generated by scripts/prepare-listening.py; edit scripts/listening sources.\nimport type { ListeningLesson } from "./types";\n\nexport const listeningLessons: ListeningLesson[] = '+json.dumps(output,ensure_ascii=False,indent=2)+';\n')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--audio-dir',type=Path,required=True)
    prepare(parser.parse_args().audio_dir)
