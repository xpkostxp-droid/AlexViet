#!/usr/bin/env python3
"""Prepare recorded listening sprites from the reviewed source manifest.

Requires ffmpeg and the original 01.mp3..59.mp3 files. Never runs in the browser.
"""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
RATE = 22050

def prepare(audio_dir: Path):
    manifest = json.loads((ROOT / 'scripts/listening/phrasebook2/source-manifest.json').read_text())
    assert [x['number'] for x in manifest] == list(range(1, 60))
    output = ROOT / 'public/audio/phrasebook2'
    output.mkdir(parents=True, exist_ok=True)
    lessons = []
    for entry in manifest:
        n = entry['number']
        pcm = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(audio_dir / f'{n:02}.mp3'), '-f', 's16le', '-ac', '1', '-ar', str(RATE), '-'])
        combined = bytearray()
        phrases = []
        for i, phrase in enumerate(entry['phrases']):
            a, b = round(phrase['sourceStart'] * RATE), round(phrase['sourceEnd'] * RATE)
            assert 0 <= a < b <= len(pcm) // 2, (n, i, a, b)
            start = len(combined) / (RATE * 2)
            combined.extend(pcm[a * 2:b * 2])
            end = len(combined) / (RATE * 2)
            combined.extend(bytes(RATE * 2))
            phrases.append({'id': f'pb2-{n:02}-{i + 1:02}', 'vi': phrase['vi'], 'ru': phrase['ru'], 'start': round(start, 6), 'end': round(end, 6)})
        with tempfile.NamedTemporaryFile(suffix='.mp3', dir=output) as temporary:
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's16le', '-ar', str(RATE), '-ac', '1', '-i', 'pipe:0', '-codec:a', 'libmp3lame', '-b:a', '80k', temporary.name], input=combined, check=True)
            Path(temporary.name).replace(output / f'{n:02}.mp3')
        lessons.append({'id': f'phrasebook2-{n:02}', 'number': n, 'title': entry['title'], 'audio': f'audio/phrasebook2/{n:02}.mp3', 'vocabulary': entry['vocabulary'], 'phrases': phrases})
    text = "// Generated by scripts/prepare-phrasebook2.py; edit the reviewed source manifest.\nimport type { ListeningLesson } from './types';\n\nexport const phrasebook2Lessons: ListeningLesson[] = "
    (ROOT / 'src/content/listening/phrasebook2.ts').write_text(text + json.dumps(lessons, ensure_ascii=False, indent=2) + ';\n')
    print(f'Prepared {len(lessons)} lessons / {sum(len(x["phrases"]) for x in lessons)} prompts')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--audio-dir', required=True, type=Path)
    prepare(parser.parse_args().audio_dir)
